#!/usr/bin/env python3
"""One-time WorkFlowOS setup. Creates your .env and checks it works.

    python setup.py

It never overwrites an existing .env, writes UTF-8 without a BOM (so Windows
PowerShell cannot silently corrupt the first variable), and finishes by running
the preflight checks.
"""
import getpass
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ENV_PATH = os.path.join(HERE, ".env")
EXAMPLE = os.path.join(HERE, ".env.example")

DEFAULTS = {
    "LLM_BASE_URL": "https://api.groq.com/openai/v1",
    "LLM_MODEL": "llama3-8b-8192",
    "GMAIL_CREDENTIALS": "./python/credentials.json",
    "GMAIL_TOKEN": "./python/token.json",
    "DOWNLOAD_DIR": "./python/downloads",
    "CRM_URL": "http://localhost:8080",
    "PYTHON_EXECUTOR_URL": "http://localhost:8082",
    "PYTHON_EXECUTOR_PORT": "8082",
    "PORT": "8080",
    "DEMO_MODE": "false",
    "DRY_RUN": "false",
}

BANNER = r"""
  WorkFlowOS setup
  ----------------
  Press Enter to skip any optional value.
"""


INTERACTIVE = sys.stdin.isatty()


def ask(prompt, secret=False, default=""):
    suffix = f" [{'set' if default else 'skip'}]" if default else ""
    # getpass reads the console directly on Windows, so it ignores piped input
    # and would hang in CI. Fall back to input() whenever there is no TTY.
    reader = getpass.getpass if (secret and INTERACTIVE) else input
    try:
        value = reader(f"  {prompt}{suffix}: ").strip()
    except EOFError:
        # No more input (piped or redirected): fall back to the default rather
        # than aborting, so `--skip-everything` style runs still produce a file.
        return default
    except KeyboardInterrupt:
        print("\n  cancelled.")
        raise SystemExit(1)
    return value or default


def main():
    if os.path.exists(ENV_PATH):
        print(f"  .env already exists at {ENV_PATH} - leaving it untouched.")
        print("  Delete it first if you want to start over.")
        sys.stdout.flush()
        return run_doctor()

    if not os.path.exists(EXAMPLE):
        print(f"  {EXAMPLE} is missing; cannot generate .env")
        return 1

    print(BANNER)
    print("  Slack incoming webhook")
    print("    https://api.slack.com/apps -> From scratch -> Incoming Webhooks")
    print("    -> Activate New Webhooks -> pick a channel -> Copy Webhook URL")
    webhook = ask("SLACK_WEBHOOK_URL")

    print("\n  LLM key (optional, free, no card)")
    print("    Groq:       https://console.groq.com/keys")
    print("    OpenRouter: https://openrouter.ai/keys  (free models)")
    print("  Without a key, workflow generation uses the local template, which")
    print("  still works on real emails.")
    api_key = ask("LLM_API_KEY", secret=True)

    provider = "Groq"
    if api_key:
        answer = ask("Provider? [g]roq / [o]penrouter", default="g").lower()
        provider = "OpenRouter" if answer.startswith("o") else "Groq"

    values = dict(DEFAULTS)
    values["SLACK_WEBHOOK_URL"] = webhook
    values["LLM_API_KEY"] = api_key
    if provider == "OpenRouter":
        values["LLM_BASE_URL"] = "https://openrouter.ai/api/v1"
        values["LLM_MODEL"] = "meta-llama/llama-3-8b-instruct:free"
        print("  -> switched to OpenRouter free tier (edit .env to change back)")
    elif api_key:
        print("  -> using Groq (edit .env to change provider, no code change)")

    lines = [
        "# WorkFlowOS local configuration. Gitignored - do not commit.",
        "# Generated by setup.py",
        "",
        f"DEMO_MODE={values['DEMO_MODE']}",
        f"DRY_RUN={values['DRY_RUN']}",
        "",
        f"SLACK_WEBHOOK_URL={webhook}",
        "",
        f"LLM_API_KEY={api_key}",
        f"LLM_BASE_URL={values['LLM_BASE_URL']}",
        f"LLM_MODEL={values['LLM_MODEL']}",
        "",
        f"GMAIL_CREDENTIALS={values['GMAIL_CREDENTIALS']}",
        f"GMAIL_TOKEN={values['GMAIL_TOKEN']}",
        "",
        f"DOWNLOAD_DIR={values['DOWNLOAD_DIR']}",
        f"CRM_URL={values['CRM_URL']}",
        f"PYTHON_EXECUTOR_URL={values['PYTHON_EXECUTOR_URL']}",
        f"PYTHON_EXECUTOR_PORT={values['PYTHON_EXECUTOR_PORT']}",
        f"PORT={values['PORT']}",
        "",
    ]

    # encoding="utf-8" writes no BOM. Never use "utf-8-sig" here: a BOM would
    # become part of the first variable's name and break it silently.
    with open(ENV_PATH, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))

    raw = open(ENV_PATH, "rb").read()
    if raw[:3] == b"\xef\xbb\xbf":
        print("  ERROR: a BOM was written; delete .env and run again")
        return 1

    print(f"\n  Wrote {os.path.relpath(ENV_PATH, HERE)} (no BOM, {len(raw)} bytes)")
    print("  Gmail is authorized on first run via a browser consent window.")
    sys.stdout.flush()  # keep our output ahead of the subprocess's
    return run_doctor()


def run_doctor():
    print("\n" + "=" * 58 + "\n")
    sys.stdout.flush()
    import subprocess
    result = subprocess.run([sys.executable, os.path.join(HERE, "doctor.py")], cwd=HERE)
    print("Next:")
    print("  1) Terminal 1:  cd go     && go run cmd/server/main.go")
    print("  2) Terminal 2:  cd python && python -m executor.server")
    print("  3) See real mail: python doctor.py --inbox")
    print("  4) Real run:      python live_run.py --run --slack")
    sys.stdout.flush()
    return result.returncode


if __name__ == "__main__":
    sys.exit(main())
